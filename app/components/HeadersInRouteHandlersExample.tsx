/* Headers In Route Handlers:- HTTP Header represent the metada associated with an API request and response.

Request Headers:-
These are sent by the client, such as web browser, to the server. they contain essential information about the
request, which helps the server understand and process it correctly.
-> "User-agent" which identifies the browser and operating system to the server.
-> "Accept" which indicates the content types like text, video or image formats that the client can process.
-> "authorization" header used by the client to authenticate itself to the server.

Response Headers:-
-> These are sent back from the server to the client. They provide information about the server and the data being sent in response.
-> "content-type" Example Application/json
*/